-- ===============================================================================================
/* Question 5: Revenue Per Product
Calculate the total revenue generated by each product. 
-
- Revenue Formula
- Quantity x Product Price x (1 - Discount)
-
- Business Objective:
- Identify products generating the highest revenue.*/
-- ===============================================================================================

select
	p.product_id,
    p.product_name,
    sum(oi.quantity * p.price * (1 - oi.discount)) as total_revenue
from products as p
join order_items as oi
	on p.product_id = oi.product_id
group by p.product_id, p.product_name
order by total_revenue desc;

-- ===============================================================================================
-- Question 6: Revenue Per Customer
-- Calculate the total revenue generated by each customer. 
-- 
-- Business Objective 
--  Identify high_value customers based on their 
-- contribution to toal revenue 
-- ===============================================================================================

select
	c.customer_id,
    c.customer_name,
    sum(oi.quantity * p.price * (1 - oi.discount)) as total_revenue
from customers as c
join orders as o
	on c.customer_id = o.customer_id
join order_items as oi
	on o.order_id = oi.order_id
join products as p
	on oi.product_id = p.product_id
group by c.customer_id, c.customer_name
order by total_revenue desc;

-- ===============================================================================================
/* Question 7: Revenue by Category
Calculate the total revenue generated by each product category 
- 
- Business Objective:
- Compare category performance and identify the 
- categories contributing the most revenue. */
-- ===============================================================================================

select 
	c.category_id,
    c.category_name,
    sum(oi.quantity * p.price * (1 - oi.discount)) as total_revenue
from categories as c
join products as p
	on c.category_id = p.category_id
join order_items as oi
	on p.product_id = oi.product_id
join orders as o
	on oi.order_id = o.order_id
group by c.category_id, c.category_name
order by total_revenue desc;

-- ===============================================================================================
-- Question 8: Customers Above #500,000
-- Identify customers who generated more than #500,000 in total revenu
--
-- Business Objective 
-- Identify high-revenue customers who may require 
-- targeted relationship management and retention strategies 
-- ===============================================================================================


select
	c.customer_id,
    c.customer_name,
    sum(oi.quantity * p.price * (1 - oi.discount)) as total_revenue
from customers as c
join orders as o
	on c.customer_id = o.customer_id
join order_items as oi
	on o.order_id = oi.order_id
join products as p
	on oi.product_id = p.product_id
group by c.customer_id, c.customer_name
having sum(oi.quantity * p.price * (1 - oi.discount)) > 500000
order by total_revenue desc
;

-- ===============================================================================================
-- Question 9: Case + Aggregation 
-- Classify customers based on their total revenue.
-- 
-- Classification
-- ₦1,000,000 or more → High Value
-- ₦500,000 or more   → Medium Value
-- Below ₦500,000     → Low Value
--
-- Business Objective:
-- segment customers according to their revenue contribution
-- to support customer management and sales strategies. 
-- ===============================================================================================

with customer_revenue as (
select
	c.customer_id,
    c.customer_name,
    sum(oi.quantity * p.price * (1 - oi.discount)) as total_revenue
from customers as c
join orders as o
	on c.customer_id = o.customer_id
join order_items as oi
	on o.order_id = oi.order_id
join products as p
	on oi.product_id = p.product_id
group by c.customer_id, c.customer_name) 
select 
	customer_id,
    customer_name,
    total_revenue,
case
	when total_revenue >= 1000000 then  "High Value"
    when total_revenue >= 500000 then "Medium Value"
    else "Low Value"
end as customer_Level
from customer_revenue
order by total_revenue desc;
